// Builds src/data/story/clips.js (clip id -> [speaker, text, choice, option]) from the scenario package's
// voice-recording manifest (Реплики.json). Clip ids are stable: new lines get new ids, old ones are never renumbered.
//   node tools/story/gen_clips.mjs <path/to/Реплики.json>
import { readFileSync, writeFileSync } from 'node:fs';
const src = process.argv[2];
if (!src) { console.error('usage: node tools/story/gen_clips.mjs <Реплики.json>'); process.exit(2); }
const d = JSON.parse(readFileSync(src, 'utf8'));
// Lines the export missed (an answer with nested quotes was not recognised): new ids, appended once.
const EXTRA = [
  { id: 'B06a_010', speaker: 'МЕГУМИН', text: 'Когда скажу «дорога чиста», выходишь.', kind: 'player_choice', choice: 'B06a.1', option: 1 }, // docs/story/04 line 233
];
for (const e of EXTRA) if (!d.clips.some((c) => c.id === e.id)) d.clips.push(e);
const q = (s) => JSON.stringify(s);
const lines = d.clips.map((c) => {
  const extra = c.kind === 'player_choice' ? `, ${q(c.choice)}, ${c.option}` : '';
  return `  ${c.id}: [${q(c.speaker)}, ${q(c.text)}${extra}],`;
});
const out = `/**
 * Spoken lines of the scenario package (docs/story): id -> [speaker, text] (+ [choice id, option no.] for the
 * lines Megumin says when she picks an answer). GENERATED by tools/story/gen_clips.mjs. The ids are the
 * recording ids of the future voice-over; dialogue scenes (data/story/*.js) reference them and never copy text.
 */
export const CLIPS = {
${lines.join('\n')}
};
`;
writeFileSync('src/data/story/clips.js', out);
console.log('clips:', d.clips.length, 'bytes:', out.length);
