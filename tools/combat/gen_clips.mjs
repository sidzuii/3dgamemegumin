// Spoken lines of the combat description (docs/combat/Реплики_для_боевки.txt) -> src/data/story/combatClips.js.
// Same shape as the scenario clips ([speaker, text]); ids CB01_*, CB02_*, CB_M*, CB_R* are the future voice-over ids.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../../docs/combat/Реплики_для_боевки.txt', import.meta.url), 'utf8');
const out = {};
for (const block of src.split(/\n(?=\[)/)) {
  const m = block.match(/^\[([A-Z0-9_]+)\]\s+(\S+)/);
  const t = block.match(/Текст:\s*(.+)/);
  if (m && t) out[m[1]] = [m[2], t[1].trim()];
}
let js = '/**\n * Spoken lines of the combat description (docs/combat/Реплики_для_боевки.txt): id -> [speaker, text].\n'
  + ' * GENERATED by tools/combat/gen_clips.mjs; the scenario lines of clips.js keep their ids untouched.\n */\nexport const COMBAT_CLIPS = {\n';
for (const [k, v] of Object.entries(out)) js += `  ${k}: [${JSON.stringify(v[0])}, ${JSON.stringify(v[1])}],\n`;
js += '};\n';
writeFileSync(new URL('../../src/data/story/combatClips.js', import.meta.url), js);
console.log(Object.keys(out).length, 'lines');
