const esc = (value) => String(value).replace(/[&<>"']/g, (c) => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

export function iconHtml(id, { size = 40, baseUrl } = {}) {
  const icon = ICONS[id];
  if (!icon) return '';
  const px = Math.max(16, Math.min(256, Number(size) || 40));
  const root = baseUrl ?? `${import.meta.env?.BASE_URL ?? '/'}ui/icons/`;
  const url = `${root.endsWith('/') ? root : root + '/'}${icon.file}`;
  const { x, y, w, h } = icon.frame;
  const bx = x / (icon.atlasWidth - w) * 100;
  const by = y / (icon.atlasHeight - h) * 100;
  const sx = icon.atlasWidth / w * 100;
  const sy = icon.atlasHeight / h * 100;
  const scale = px * 0.86 / Math.max(w, h);
  return `<span class="mg-icon" role="img" aria-label="${esc(icon.name)}" style="--mg-icon-size:${px}px"><span class="mg-icon-image" style="width:${w*scale}px;height:${h*scale}px;background-image:url('${esc(url)}');background-position:${bx}% ${by}%;background-size:${sx}% ${sy}%"></span></span>`;
}

